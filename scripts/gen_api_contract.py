#!/usr/bin/env python3
"""Generate the frontend/backend API contract from the backend's OpenAPI spec.

Writes frontend/src/types/api.gen.ts:
  * one TypeScript type per OpenAPI component schema (the backend's Pydantic
    models), as the backend actually sends or accepts it;
  * API_OPERATIONS: every "METHOD /path" the backend serves under /api/v1.

The frontend keeps its own hand-written types (src/types/index.ts). The
compile-time checks in src/types/contract.ts and the Vitest test
src/types/contract.test.ts compare them with this file, so a backend change that
the frontend does not follow fails `npm run typecheck` / `npm test`, and a
backend change without regenerating this file fails the backend test
tests/unit/test_api_contract.py.

Usage (backend virtualenv active, from the repository root):
  python scripts/gen_api_contract.py          # rewrite the file
  python scripts/gen_api_contract.py --check  # exit 1 if it is out of date

No dependencies beyond the backend's own; no database needed.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "frontend" / "src" / "types" / "api.gen.ts"
API_PREFIX = "/api/v1"

HEADER = """\
// GENERATED by scripts/gen_api_contract.py from the backend's OpenAPI spec.
// DO NOT EDIT. Regenerate: python scripts/gen_api_contract.py (backend venv).
// Checked against src/types/index.ts by src/types/contract.ts (typecheck) and
// src/types/contract.test.ts (paths); kept current by the backend test
// tests/unit/test_api_contract.py.
"""

_IDENT = re.compile(r"[^A-Za-z0-9_]")


def type_name(schema_name: str, *, request: bool = False) -> str:
    """Page[JobSummary] is `Page_JobSummary_` in OpenAPI; keep it a valid identifier.

    Response shapes keep the schema's name; request shapes get an `Input` suffix.
    """
    return _IDENT.sub("_", schema_name) + ("Input" if request else "")


def load_spec() -> dict[str, Any]:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.core.config import Settings
    from app.main import create_app

    settings = Settings(_env_file=None, database_url="postgresql://u:p@127.0.0.1:1/unused")
    return create_app(settings).openapi()


def _refs(node: Any) -> set[str]:
    found: set[str] = set()
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            found.add(ref.rsplit("/", 1)[1])
        for value in node.values():
            found |= _refs(value)
    elif isinstance(node, list):
        for value in node:
            found |= _refs(value)
    return found


def _closure(names: set[str], schemas: dict[str, Any]) -> set[str]:
    seen: set[str] = set()
    todo = list(names)
    while todo:
        name = todo.pop()
        if name in seen or name not in schemas:
            continue
        seen.add(name)
        todo.extend(_refs(schemas[name]))
    return seen


def schema_usage(spec: dict[str, Any]) -> tuple[set[str], set[str]]:
    """(schemas reachable from responses, schemas reachable from request bodies/params)."""
    schemas = spec["components"]["schemas"]
    out: set[str] = set()
    inp: set[str] = set()
    for item in spec["paths"].values():
        for op in item.values():
            out |= _refs(op.get("responses", {}))
            inp |= _refs(op.get("requestBody", {})) | _refs(op.get("parameters", []))
    return _closure(out, schemas), _closure(inp, schemas)


def ts_literal(value: Any) -> str:
    return json.dumps(value)


def ts_type(node: dict[str, Any], *, all_required: bool, indent: str = "") -> str:
    """all_required=True renders the response shape, False the request shape."""
    if not node:
        return "unknown"
    if "$ref" in node:
        return type_name(node["$ref"].rsplit("/", 1)[1], request=not all_required)
    if "const" in node:
        return ts_literal(node["const"])
    if "enum" in node:
        return " | ".join(ts_literal(v) for v in node["enum"])
    for key in ("anyOf", "oneOf"):
        if key in node:
            parts = [ts_type(n, all_required=all_required, indent=indent) for n in node[key]]
            return " | ".join(dict.fromkeys(parts))
    if "allOf" in node:
        parts = [ts_type(n, all_required=all_required, indent=indent) for n in node["allOf"]]
        return " & ".join(dict.fromkeys(parts))
    kind = node.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**node, "type": k}, all_required=all_required) for k in kind)
    if kind == "null":
        return "null"
    if kind == "boolean":
        return "boolean"
    if kind in ("integer", "number"):
        return "number"
    if kind == "string":
        return "string"
    if kind == "array":
        items = ts_type(node.get("items", {}), all_required=all_required, indent=indent)
        if "prefixItems" in node:
            tup = ", ".join(
                ts_type(n, all_required=all_required, indent=indent) for n in node["prefixItems"]
            )
            return f"[{tup}]"
        return f"({items})[]" if "|" in items or "&" in items else f"{items}[]"
    if kind == "object" or "properties" in node:
        props = node.get("properties")
        if props:
            return ts_object(node, all_required=all_required, indent=indent)
        extra = node.get("additionalProperties", True)
        value = "unknown" if extra in (True, {}) else ts_type(extra, all_required=all_required)
        return f"Record<string, {value}>"
    return "unknown"


def ts_object(node: dict[str, Any], *, all_required: bool, indent: str) -> str:
    required = set(node.get("required", []))
    inner = indent + "  "
    lines = ["{"]
    for prop, sub in node["properties"].items():
        optional = "" if (all_required or prop in required) else "?"
        key = prop if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", prop) else json.dumps(prop)
        value = ts_type(sub, all_required=all_required, indent=inner)
        lines.append(f"{inner}{key}{optional}: {value};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def operations(spec: dict[str, Any]) -> list[str]:
    ops = []
    for path, item in spec["paths"].items():
        if not path.startswith(API_PREFIX + "/"):
            continue
        for method in item:
            ops.append(f"{method.upper()} {path[len(API_PREFIX) :]}")
    return sorted(ops)


def render(spec: dict[str, Any]) -> str:
    schemas = spec["components"]["schemas"]
    responses, requests = schema_usage(spec)
    out = [HEADER]
    for name in sorted(schemas):
        node = schemas[name]
        doc = node.get("description") or node.get("title") or name
        first = doc.strip().splitlines()[0].replace("*/", "* /")
        # A response always carries every field (no route excludes unset or None
        # values), even fields with defaults that OpenAPI lists as optional; a
        # request body may leave those out.
        if name in responses:
            out.append(f"/** {first} (as the backend sends it) */")
            out.append(f"export type {type_name(name)} = {ts_type(node, all_required=True)};\n")
        if name in requests:
            out.append(f"/** {first} (as the backend accepts it) */")
            shape = ts_type(node, all_required=False)
            out.append(f"export type {type_name(name, request=True)} = {shape};\n")
    out.append("/** Every operation the backend serves under /api/v1. */")
    out.append("export const API_OPERATIONS = [")
    out.extend(f"  {json.dumps(op)}," for op in operations(spec))
    out.append("] as const;\n")
    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = parser.parse_args()
    content = render(load_spec())
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if args.check:
        if current != content:
            name = OUTPUT.relative_to(ROOT)
            print(f"{name} is out of date: run python scripts/gen_api_contract.py")
            return 1
        print("API contract is up to date")
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
